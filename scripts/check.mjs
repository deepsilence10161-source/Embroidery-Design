import {readFile,readdir} from 'node:fs/promises';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const html=await readFile('EmbroideryGuide.html','utf8');
const pkg=JSON.parse(await readFile('package.json','utf8'));
const markup=html.replace(/<script>[\s\S]*?<\/script>/,'<script></script>');
assert.equal((markup.match(/<style>/g)||[]).length,1,'Canonical file must have one head style');
assert.equal((html.match(/<script>/g)||[]).length,1,'Canonical file must have one inline body script');
assert(html.indexOf('</style>')<html.indexOf('</head>'));
assert(/<script>[\s\S]*<\/script>\s*<\/body>/.test(html));
assert(!/<(?:script|link|img)\b[^>]*(?:src|href)=["'](?:https?:)?\/\//i.test(html),'No external runtime assets');
assert(!html.includes('__EG_TEST_ONLY__'),'Do not ship test hooks');
assert(html.includes(`const VERSION = '${pkg.version}'`),'Version mismatch');
new vm.Script(html.match(/<script>([\s\S]*?)<\/script>/)[1]);
for(const key of ['embroidery_designs','embroidery_colors','embroidery_settings'])assert(html.includes(key));
const cap=JSON.parse(await readFile('capacitor.config.json','utf8'));
assert.equal(cap.appId,'com.embroideryguide.app');assert.equal(cap.webDir,'.native-web');assert(!cap.server?.url,'Android must bundle the app, never load the hosted site');
for(const dir of ['src','scripts'])for(const file of await readdir(dir))if(file.endsWith('.mjs')||file.endsWith('.js'))execFileSync(process.execPath,['--check',`${dir}/${file}`],{stdio:'inherit'});
console.log('PASS single source, inline assets, syntax, matching versions, storage compatibility and offline native config.');
